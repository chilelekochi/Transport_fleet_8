CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id INT)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE v_due BOOLEAN;
BEGIN
 SELECT current_odometer-last_service_odometer>=5000 INTO v_due
 FROM vehicles WHERE vehicle_id=p_vehicle_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID: %',p_vehicle_id; END IF;
 RETURN v_due;
END $$;

CREATE OR REPLACE FUNCTION trg_update_odometer()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC(12,2);
BEGIN
 SELECT current_odometer INTO v_current FROM vehicles
 WHERE vehicle_id=NEW.vehicle_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID'; END IF;
 IF NEW.end_odometer<=NEW.start_odometer THEN
   RAISE EXCEPTION 'End odometer must be greater than start odometer';
 END IF;
 IF NEW.start_odometer<>v_current THEN
   RAISE EXCEPTION 'Trip must start at current odometer value (%)',v_current;
 END IF;
 UPDATE vehicles SET current_odometer=NEW.end_odometer
 WHERE vehicle_id=NEW.vehicle_id;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_trip_odometer
BEFORE INSERT ON trips
FOR EACH ROW EXECUTE FUNCTION trg_update_odometer();

CREATE OR REPLACE PROCEDURE pr_record_trip(
 p_vehicle_id INT,p_trip_on DATE,p_start NUMERIC,p_end NUMERIC)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM vehicles WHERE vehicle_id=p_vehicle_id) THEN
   RAISE EXCEPTION 'Unknown vehicle ID: %',p_vehicle_id;
 END IF;
 IF p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL OR p_end<=p_start THEN
   RAISE EXCEPTION 'Provide a trip date and valid increasing odometer values';
 END IF;
 INSERT INTO trips(vehicle_id,trip_on,start_odometer,end_odometer)
 VALUES(p_vehicle_id,p_trip_on,p_start,p_end);
 -- The BEFORE INSERT trigger updates the vehicle odometer exactly once.
END $$;

CREATE OR REPLACE VIEW v_service_due AS
SELECT registration,current_odometer-last_service_odometer AS km_since_service
FROM vehicles WHERE current_odometer-last_service_odometer>=5000;

CREATE INDEX idx_trips_vehicle_date ON trips(vehicle_id,trip_on);
EXPLAIN SELECT trip_id,trip_on,start_odometer,end_odometer
FROM trips WHERE vehicle_id=1
AND trip_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_service_alerts()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO service_alerts(vehicle_id,km_since_service,flagged_on)
 SELECT vehicle_id,current_odometer-last_service_odometer,CURRENT_DATE
 FROM vehicles WHERE current_odometer-last_service_odometer>=5000
 ON CONFLICT(vehicle_id) DO UPDATE SET
 km_since_service=EXCLUDED.km_since_service,flagged_on=EXCLUDED.flagged_on;
 DELETE FROM service_alerts a USING vehicles v
 WHERE a.vehicle_id=v.vehicle_id
   AND v.current_odometer-v.last_service_odometer<5000;
END $$;

