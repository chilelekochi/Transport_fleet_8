CREATE SCHEMA IF NOT EXISTS q8_fleet;
SET search_path TO q8_fleet, public;

DROP VIEW IF EXISTS v_service_due;
DROP TABLE IF EXISTS service_alerts,trips,vehicles CASCADE;
DROP FUNCTION IF EXISTS fn_service_due(INT);
DROP PROCEDURE IF EXISTS pr_record_trip(INT,DATE,NUMERIC,NUMERIC);
DROP PROCEDURE IF EXISTS pr_refresh_service_alerts();

CREATE TABLE vehicles (
 vehicle_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registration VARCHAR(20) NOT NULL UNIQUE,
 current_odometer NUMERIC(12,2) NOT NULL CHECK(current_odometer>=0),
 last_service_odometer NUMERIC(12,2) NOT NULL CHECK(last_service_odometer>=0 AND last_service_odometer<=current_odometer)
);
CREATE TABLE trips (
 trip_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id INT NOT NULL REFERENCES vehicles(vehicle_id),
 trip_on DATE NOT NULL,
 start_odometer NUMERIC(12,2) NOT NULL CHECK(start_odometer>=0),
 end_odometer NUMERIC(12,2) NOT NULL CHECK(end_odometer>=0)
);
CREATE TABLE service_alerts (
 vehicle_id INT PRIMARY KEY REFERENCES vehicles(vehicle_id),
 km_since_service NUMERIC(12,2) NOT NULL,
 flagged_on DATE NOT NULL
);
